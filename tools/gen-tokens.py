#!/usr/bin/env python3
"""Делает src/theme/tokens.css из tools/figma-tokens.json (значения переменных и текстовых стилей из Figma).
Запуск:  python3 tools/gen-tokens.py
Поменяли цвет, отступ или стиль текста в Figma → поправили figma-tokens.json → запустили скрипт. Код трогать не нужно."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = json.load(open(os.path.join(ROOT, 'tools', 'figma-tokens.json'), encoding='utf-8'))


def var(name):
    return '--' + name.replace('/', '-')


def value(v):
    return f'{v}px' if isinstance(v, (int, float)) else v


out = ['/* GENERATED by tools/gen-tokens.py from tools/figma-tokens.json — не правьте вручную. */', '']
themes = data['themes']
first = next(iter(themes))
out.append(f':root, [data-theme="{first}"] {{')
for k, v in themes[first].items():
    out.append(f'  {var(k)}: {value(v)};')
for k, v in data['spacing'].items():
    out.append(f'  {var(k)}: {value(v)};')
out.append('}')
for name, vals in list(themes.items())[1:]:
    out.append(f'\n[data-theme="{name}"] {{')
    for k, v in vals.items():
        out.append(f'  {var(k)}: {value(v)};')
    out.append('}')

out.append('\n/* Текстовые стили Aura: класс .t-<имя> = стиль «Aura/…» в Figma */')
for name, spec in data['text'].items():
    weight, size, lh, ls = spec[:4]
    extra = spec[4:] if len(spec) > 4 else []
    rules = [f'font-weight: {weight}', f'font-size: {size}px',
             f'line-height: {"normal" if lh == "auto" else str(lh) + "px"}', f'letter-spacing: {ls / 100:g}em']
    if 'italic' in extra:
        rules.append('font-style: italic')
    if 'upper' in extra:
        rules.append('text-transform: uppercase')
    out.append(f'.t-{name} {{ {"; ".join(rules)}; }}')

open(os.path.join(ROOT, 'src', 'theme', 'tokens.css'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('tokens.css:', len(themes), 'themes,', len(data['text']), 'text styles')
